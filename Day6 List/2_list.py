#List :
x = [10,20.5,"om",[11,22,33]]
print(x)   #[10, 20.5, 'om', [11, 22, 33]] #List stores everything exactly as you write it

l = [10,20,30,10,10,10,10,10]
print(l)   #[10, 20, 30, 10, 10, 10, 10, 10] ✅ List allows duplicate values.

l = {10,20,30,10,10,10,10,10}
print(l)    #{10, 20, 30} #Set does NOT allow duplicate values.

