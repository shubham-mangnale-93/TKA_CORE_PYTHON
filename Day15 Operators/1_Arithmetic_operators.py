'''
Arithmetic Operators : It is used to perform mathematical operations
like addition, subtraction, multiplication, division etc. between
two values or expressions.

1) +   -> Addition          : adds two values
2) -   -> Subtraction       : subtracts right value from left
3) *   -> Multiplication    : multiplies two values
4) /   -> Division          : divides and gives float result
5) //  -> Floor Division    : divides and gives whole number (removes decimal)
6) %   -> Modulus           : gives remainder after division
7) **  -> Exponent (Power)  : raises left value to power of right
'''

a = 17
b = 5

print(a + b)    # 22   -> Addition
print(a - b)    # 12   -> Subtraction
print(a * b)    # 85   -> Multiplication
print(a / b)    # 3.4  -> Division (float result)
print(a // b)   # 3    -> Floor Division (decimal removed)
print(a % b)    # 2    -> Modulus (remainder)
print(a ** b)   # 1419857  -> Exponent (17 raised to power 5)