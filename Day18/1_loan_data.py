# Q9] Calculate EMI for Every Customer
'''
Calculate the Monthly EMI for every customer using:
Loan Amount
Interest Rate
Loan Tenure

Display:
Customer Name
Loan Amount
Monthly EMI
'''
for loan_id, details in loan_data.items():

    # Step 1: Get Loan Details
    principal = details["loan_amount"]
    annual_rate = details["interest_rate"]
    years = details["tenure_years"]

    # Step 2: Convert Annual Interest Rate to Monthly Interest Rate
    r = (annual_rate / 12) / 100

    # Step 3: Convert Years to Months
    n = years * 12

    # Step 4: Calculate EMI
    emi = (principal * r * (1 + r) ** n) / ((1 + r) ** n - 1)

    # Step 5: Display Output
    print("Loan ID       :", loan_id)
    print("Customer Name :", details["customer_name"])
    print("Loan Amount   :", principal)
    print("Interest Rate :", annual_rate, "%")
    print("Tenure        :", years, "Years")
    print("Monthly EMI   :", round(emi, 2))
    print("-" * 50)
